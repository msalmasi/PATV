// postmd.js — the feed's opt-in Markdown grammar, shared by posts and comments.
// Parse source into small nodes BEFORE rendering: emphasis never examines generated links or HTML,
// and code/unsupported links bypass the ordinary feed inline pipeline. No raw HTML or placeholders.
// mdlite's escaping/scheme check are shared; its docs-only grammar (H1, tables, masked links) is not.
"use strict";

const { esc, safeHref } = require("./mdlite");
const inline = require("./feedinline");
const LINK_ATTRS = ' rel="nofollow noopener noreferrer ugc" target="_blank"';
const MARKS = { "**": "strong", "__": "u", "~~": "del", "||": "spoiler", "*": "em", "_": "em" };
const MAX_DEPTH = 12;
const SPOILER = "[spoiler]";              // 1.99aij: what a spoiler reads in plain text (plain() below)
const source = (value) => String(value == null ? "" : value).replace(/\r\n?/g, "\n");
const word = (c) => !!c && /[\p{L}\p{N}_]/u.test(c);

function httpHref(value) {
  const s = String(value);
  // URL() would silently discard tabs/newlines and trim controls. Reject them before validation.
  if (!/^https?:\/\//i.test(s) || /[\s\u0000-\u001f\u007f]/u.test(s) || safeHref(s) !== s) return null;
  try { const u = new URL(s); return u.protocol === "http:" || u.protocol === "https:" ? s : null; }
  catch (e) { return null; }
}

function originFor(options) {
  const fallback = process.env.STAGING ? "https://staging.publicaccess.tv" : "https://publicaccess.tv";
  const h = httpHref(options.origin || process.env.SITE_URL || fallback);
  return h ? new URL(h).origin : fallback;
}

function textHtml(text, options) {
  // Only THESE relative links, generated by the trusted feed pipeline, become absolute. Authored
  // Markdown links never accept a relative URL. Keep legacy/plain feed rendering entirely unchanged.
  return inline.linkify(text).replace(/<a class="(pad-ref|user-ref(?: mention)?|tag-ref)" href="(\/p\/[^"<>]*|\/u\/[^"<>]*|\/feed\?tag=[^"<>]*)">/g,
    (_, cls, href) => '<a class="' + cls + '" href="' + esc(originFor(options)) + href + '"' + LINK_ATTRS + '>');
}

// Explicit links are bounded, balanced at parentheses, and cannot cross a line. A failed/unsafe
// destination remains literal as a whole, including image syntax, rather than exposing a partial link.
function linkAt(s, start, budget) {
  let i = start + 1;
  for (; i < s.length && i - start <= 2048; i++) {
    if (--budget.left < 0 || s[i] === "\n") return null;
    if (s[i] === "]") break;
  }
  if (s[i] !== "]" || s[i + 1] !== "(") return null;
  const closeLabel = i;
  i += 2;
  const beginHref = i;
  let nesting = 1;
  for (; i < s.length && i - beginHref <= 2048; i++) {
    if (--budget.left < 0 || s[i] === "\n") return null;
    if (s[i] === "(") nesting++;
    if (s[i] === ")" && --nesting === 0) {
      return { end: i + 1, label: s.slice(start + 1, closeLabel), href: s.slice(beginHref, i) };
    }
  }
  return null;
}

function inlines(s, depth = 0, allowLinks = true) {
  const budget = { left: Math.max(256, s.length * 24) };
  function parse(start, closing, level, links) {
    const nodes = [];
    let i = start, buffer = "";
    const flush = () => { if (buffer) { nodes.push({ type: "text", text: buffer }); buffer = ""; } };
    while (i < s.length) {
      if (--budget.left < 0) { flush(); nodes.push({ type: "literal", text: s.slice(i) }); return { nodes, end: s.length, closed: false }; }
      if (s[i] === "\\" && s[i + 1] && /[\\`*_[\]{}()#+.!>|~\-]/.test(s[i + 1])) {
        // Escape the complete chat mark (** / __ / ~~ / ||), not half of it. Block detection
        // has already seen the leading backslash, so escaped headings/lists/fences stay prose.
        let count = Object.hasOwn(MARKS, s.slice(i + 1, i + 3)) ? 2 : 1;
        if (s.slice(i + 1, i + 4) === "```") count = 3;
        flush(); nodes.push({ type: "literal", text: s.slice(i + 1, i + 1 + count) }); i += count + 1; continue;
      }
      if (closing && s.startsWith(closing, i) && i > start && !/\s/.test(s[i - 1]) &&
          !(closing === "_" && word(s[i + 1]))) {
        flush(); return { nodes, end: i + closing.length, closed: true };
      }
      if (s[i] === "`") {
        const end = s.indexOf("`", i + 1);
        if (end > i + 1 && !s.slice(i + 1, end).includes("\n")) {
          flush(); nodes.push({ type: "code", text: s.slice(i + 1, end) }); i = end + 1; continue;
        }
      }
      // The full URL is an atom, including any *, _, [ or | in its path/query.
      if ((s[i] === "h" || s[i] === "H") && !/[A-Za-z0-9_]/.test(s[i - 1] || " ")) {
        const hit = /^https?:\/\/[^\s<>"'`]{2,2000}/i.exec(s.slice(i, i + 2008));
        if (hit) {
          let url = hit[0].replace(/[).,;:!?\]}]+$/, "");
          if (closing && url.endsWith(closing)) url = url.slice(0, -closing.length);
          flush(); nodes.push({ type: "url", text: url }); i += url.length; continue;
        }
      }
      const image = s[i] === "!" && s[i + 1] === "[";
      if (links && (s[i] === "[" || image)) {
        const found = linkAt(s, image ? i + 1 : i, budget);
        if (found) {
          flush();
          const href = !image && httpHref(found.href);
          nodes.push(href ? { type: "link", children: inlines(found.label, level + 1, false), href } : { type: "literal", text: s.slice(i, found.end) });
          i = found.end; continue;
        }
      }
      let mark = Object.hasOwn(MARKS, s.slice(i, i + 2)) ? s.slice(i, i + 2) : s[i];
      if (level < MAX_DEPTH && Object.hasOwn(MARKS, mark) && s[i + mark.length] &&
          !/\s/.test(s[i + mark.length]) && !(mark === "_" && word(s[i - 1]))) {
        flush();
        const child = parse(i + mark.length, mark, level + 1, links);
        if (child.closed) nodes.push({ type: MARKS[mark], children: child.nodes });
        else nodes.push({ type: "literal", text: s.slice(i, child.end) });
        i = child.end; continue;
      }
      buffer += s[i++];
    }
    flush(); return { nodes, end: i, closed: !closing };
  }
  return parse(0, null, depth, allowLinks).nodes;
}

const heading = (line) => /^(#{2,4})[ \t]+(.+)$/.exec(line);
const fence = (line) => /^```([^`]*)$/.exec(line);
const quote = (line) => /^> ?(.*)$/.exec(line);
function item(line) {
  const m = /^( *)([-*]|\d{1,9}\.)[ \t]+(.+)$/.exec(line);
  return m ? { indent: m[1].length, kind: m[2].endsWith(".") ? "ol" : "ul", text: m[3] } : null;
}
const startsBlock = (line) => heading(line) || fence(line) || quote(line) || line === "---" || (item(line) || {}).indent === 0;

function blocks(lines, depth = 0) {
  const out = [];
  let i = 0;
  function list(start, baseIndent, level) {
    const first = item(lines[start]);
    const node = { type: first.kind, items: [] };
    let at = start;
    while (at < lines.length) {
      const m = item(lines[at]);
      if (!m || m.indent !== baseIndent || m.kind !== node.type) break;
      const li = { parts: [{ type: "text", text: m.text }] };
      at++;
      while (at < lines.length && lines[at].trim()) {
        const next = item(lines[at]);
        if (next && next.indent <= baseIndent) break;
        if (next && next.indent >= baseIndent + 2 && level < 1) {
          const child = list(at, next.indent, level + 1);
          li.parts.push(child.node); at = child.end;
        } else if (/^ {2}/.test(lines[at]) && lines[at].search(/\S/) > baseIndent) {
          const continuation = lines[at].slice(baseIndent + 2), previous = li.parts[li.parts.length - 1];
          if (previous.type === "text") previous.text += "\n" + continuation;
          else li.parts.push({ type: "text", text: continuation });
          at++;
        } else break;
      }
      node.items.push(li);
    }
    return { node, end: at };
  }
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    const f = fence(line), h = heading(line), q = quote(line), li = item(line);
    if (f) {
      let end = i + 1;
      while (end < lines.length && !/^```[ \t]*$/.test(lines[end])) end++;
      if (end === lines.length) { out.push({ type: "literal", text: lines.slice(i).join("\n") }); break; }
      out.push({ type: "pre", language: f[1].trim(), text: lines.slice(i + 1, end).join("\n") });
      i = end + 1;
    } else if (h) {
      out.push({ type: "h" + h[1].length, text: h[2] }); i++;
    } else if (line === "---") {
      out.push({ type: "hr" }); i++;
    } else if (q && depth < MAX_DEPTH) {
      const quoted = [];
      while (i < lines.length && quote(lines[i])) quoted.push(quote(lines[i++])[1]);
      out.push({ type: "blockquote", children: blocks(quoted, depth + 1) });
    } else if (li && li.indent === 0) {
      const result = list(i, 0, 0); out.push(result.node); i = result.end;
    } else {
      const p = [line]; i++;
      while (i < lines.length && lines[i].trim() && !startsBlock(lines[i])) p.push(lines[i++]);
      out.push({ type: "p", text: p.join("\n") });
    }
  }
  return out;
}

function inlineHtml(nodes, options) {
  return nodes.map((n) => {
    if (n.type === "text") return textHtml(n.text, options).replace(/\n/g, "<br>");
    if (n.type === "literal") return esc(n.text).replace(/\n/g, "<br>");
    if (n.type === "url") return httpHref(n.text) ? inline.linkify(n.text) : esc(n.text);
    if (n.type === "code") return "<code>" + esc(n.text) + "</code>";
    if (n.type === "link") return inlineHtml(n.children, options) + ' (<a href="' + esc(n.href) + '"' + LINK_ATTRS + '>' + esc(n.href) + '</a>)';
    const children = inlineHtml(n.children, options);
    if (n.type === "spoiler") return '<span class="postmd-spoiler"><button type="button" aria-expanded="false">' +
      esc(options.spoilerLabel == null ? "Spoiler" : options.spoilerLabel) + '</button><span hidden>' + children + '</span></span>';
    return "<" + n.type + ">" + children + "</" + n.type + ">";
  }).join("");
}

function blockHtml(nodes, options) {
  return nodes.map((n) => {
    if (n.type === "hr") return "<hr>";
    if (n.type === "literal") return "<p>" + esc(n.text).replace(/\n/g, "<br>") + "</p>";
    if (n.type === "pre") return '<div class="postmd-code">' + (n.language ? '<div class="postmd-language">' + esc(n.language) + '</div>' : "") +
      "<pre><code>" + esc(n.text) + "</code></pre></div>";
    if (n.type === "blockquote") return "<blockquote>" + blockHtml(n.children, options) + "</blockquote>";
    if (n.type === "ul" || n.type === "ol") return "<" + n.type + ">" + n.items.map((li) =>
      "<li>" + li.parts.map((part) => part.type === "text" ? inlineHtml(inlines(part.text), options) : blockHtml([part], options)).join("") + "</li>").join("") + "</" + n.type + ">";
    return "<" + n.type + ">" + inlineHtml(inlines(n.text), options) + "</" + n.type + ">";
  }).join("\n");
}

function inlinePlain(nodes, options) {
  return nodes.map((n) => {
    if (n.type === "spoiler") return options.spoilers === "show" ? inlinePlain(n.children, options) : SPOILER;
    if (n.type === "code") return options.omitCode ? " " : n.text;
    if (n.type === "link") return inlinePlain(n.children, options) + " (" + n.href + ")";
    return n.children ? inlinePlain(n.children, options) : n.text;
  }).join("");
}

function blockPlain(nodes, options) {
  return nodes.map((n) => {
    if (n.type === "hr") return "";
    if (n.type === "literal") return n.text;
    if (n.type === "pre") return options.omitCode ? " " : n.text;
    if (n.type === "blockquote") return blockPlain(n.children, options);
    if (n.type === "ul" || n.type === "ol") return n.items.map((li) => li.parts.map((part) =>
      part.type === "text" ? inlinePlain(inlines(part.text), options) : blockPlain([part], options)).join("\n")).join("\n");
    return inlinePlain(inlines(n.text), options);
  }).join("\n\n");
}

function render(text, options = {}) { return blockHtml(blocks(source(text).split("\n")), options || {}); }
// Sticker tokens deliberately stay tokens: existing callers can apply the localized fallback.
// omitCode produces code-free readable text (closed code only). Activity/ownership checks use sourceText below.
// 1.99aij (owner 2026-11-03): a closed spoiler reads SPOILER, one word whatever it holds, so no excerpt (a notice, an
// inbox row and its Telegram alert, og tags and link previews, card labels and slugs, search snippets, Pepe's relays and
// the context his LLM reads) shows the hidden words, and no cut can land inside them. Only moderation input asks for the
// words with { spoilers: "show" } (Pepe's automod: a spoiler must not hide what a rule is about).
function plain(text, options = {}) { return blockPlain(blocks(source(text).split("\n")), options || {}); }

// Text eligible for the ordinary inline pipeline, for mention/ownership/summon checks. Keep leaf
// boundaries: @Al**i**ce must not become an @Alice notification, and a token split by code/formatting
// must not become a sticker. URLs, code and literal fallbacks never run that pipeline.
function sourceText(text) {
  const leaves = [];
  function visitInline(nodes) {
    for (const n of nodes) {
      if (n.type === "text") leaves.push(n.text);
      else if (n.children) visitInline(n.children);
    }
  }
  function visitBlocks(nodes) {
    for (const n of nodes) {
      if (n.type === "blockquote") visitBlocks(n.children);
      else if (n.items) {
        for (const li of n.items) for (const part of li.parts) {
          if (part.type === "text") visitInline(inlines(part.text)); else visitBlocks([part]);
        }
      } else if (n.type === "p" || /^h[234]$/.test(n.type)) visitInline(inlines(n.text));
    }
  }
  visitBlocks(blocks(source(text).split("\n")));
  return leaves.join("\n");
}

module.exports = { render, plain, sourceText, SPOILER };
